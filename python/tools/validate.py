def main() -> None:
    # 导出样本，供 JS 版同源对比
    (Path(__file__).resolve().parent / "samples.json").write_text(
        json.dumps([{"label": lb, "text": tx} for lb, tx in SAMPLES], ensure_ascii=False, indent=1),
        encoding="utf-8",
    )

    analyzer = DifficultyAnalyzer(verbose=True)
    print()
    print(f"{'标注':<8}{'得分':>8}  {'系统评级':<10}{'参考':<28}{'字':>7}{'词':>7}{'语法':>7}")
    print("-" * 92)
    for label, text in SAMPLES:
        r = analyzer.analyze(text)
        g = r.grade or {}
        print(
            f"{label:<8}{r.score:>8.3f}  {g.get('name', '-'):<10}{r.grade_reference:<28}"
            f"{r.chars.contribution:>7.2f}{r.words.contribution:>7.2f}{r.grammar.contribution:>7.2f}"
        )
    print()
    print("说明：字/词/语法三列分别是各维度的 Σn×r(n)（理论取值 1~7）。")


if __name__ == "__main__":
    main()
